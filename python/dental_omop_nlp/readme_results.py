def _load_judge() -> dict | None:
    """A real LLM judge run (spec 012), if one is committed; simulated dry runs are never shown."""
    if not (JUDGE_DIR / "judge_metrics.csv").exists():
        return None
    return {n: pd.read_csv(JUDGE_DIR / f"{n}.csv") for n in ("judge_metrics", "judge_agreement", "judgments")}


def base_id(method: str) -> str:
    """'modernbert-base+cw+s1+rules4' -> 'modernbert-base'."""
    return method.split("+", 1)[0]


def paired_rank_range(correct: dict, n_boot: int = N_BOOT, seed: int = SEED) -> dict:
    """95% range of each system's rank over chart resamples shared by all systems (rank 1 = best;
    tied systems share the better rank). correct: system -> boolean array, one entry per chart."""
    names = list(correct)
    c = np.array([correct[k] for k in names], dtype=float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, c.shape[1], size=(n_boot, c.shape[1]))   # same draw as ladder_eval.ladder_table
    acc = c[:, idx].mean(axis=2)                                    # systems x resamples
    ranks = 1 + (acc[None, :, :] > acc[:, None, :]).sum(axis=1)     # how many beat each system
    return {k: (int(np.floor(np.quantile(r, 0.025))), int(np.ceil(np.quantile(r, 0.975))))
            for k, r in zip(names, ranks)}


def interval_rank_range(lo, hi) -> list[tuple[int, int]]:
    return [(1 + sum(lo_j > hi_i for lo_j in lo), sum(hi_j >= lo_i for hi_j in hi)) for lo_i, hi_i in zip(lo, hi)]


def wilson(k: float, n: float, z: float = 1.96) -> tuple[float, float]:
    if not n:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def _shared_scorer():
    """eval/score.py, the scorer the R parity test checks (eval/score.R)."""
    spec = importlib.util.spec_from_file_location("eval_score", REPO_ROOT / "eval" / "score.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.score


def yes_no(truth: pd.Series, pred: pd.Series, score=None) -> dict:
    """Periodontitis (any stage) yes/no: sensitivity, specificity, PPV, NPV; no status counts as "no"."""
    res = (score or _shared_scorer())(truth, pred.fillna("none"), None, "readme")
    m = res[res["class"] == ""].set_index("metric")["value"]
    return {k: m[k] for k in ("sensitivity", "specificity", "ppv", "npv")}


PHENOTYPE_KEY = ("**Exact status right**: the share of charts given the right one of six statuses (healthy, "
                 "gingivitis, stage I–IV); no status counts as wrong. The next four ask the yes/no question *does "
                 "this patient have periodontitis?*: **Sensitivity**, of the patients who have it, the share flagged "
                 "(the rest are *missed cases*); **Specificity**, of those who don't, the share correctly cleared "
                 "(the rest are *false alarms*); **PPV**, when it says yes, how often that's right; **NPV**, when "
                 "it says no, how often that's right. No status counts as \"no\".")
DEID_KEY = ("**Identifiers caught**: the share of names, dates and IDs removed; the rest are *missed* and leak "
            "(one character left counts). **Removals that were identifiers**: of everything removed, the share "
            "that really was an identifier; the rest is ordinary text removed by mistake, the *false alarms*. "
            "The damage columns count the same false alarms on dental terms, clinical text and clean queries.")


def _pct(x, d=0) -> str:
    return "–" if pd.isna(x) else f"{x:.{d}%}"


def _ci(x, lo, hi, d=1) -> str:
    return f"**{x:.{d}%}** ({lo:.{d}%}–{hi:.{d}%})"


def _rank(r: tuple[int, int]) -> str:
    return str(r[0]) if r[0] == r[1] else f"{r[0]}–{r[1]}"


def _model_method(method: str) -> str:
    b = base_id(method)
    s = ("rules (regex)" if b == "note_rules" else
         "TF-IDF + logistic regression" if b == "tfidf_logreg" else
         "TF-IDF + radiograph features" if b == "fusion_tfidf_rad" else
         "zero-shot LLM" if b.startswith("medgemma") else "fine-tuned encoder")
    mods = {"cw": "class-weighted", "s1": "seed 1", "s2": "seed 2", "rules4": "+ rules for stage IV"}
    return ", ".join([s, *[mods[m] for m in method.split("+")[1:] if m in mods]])


def phenotype_systems(inp) -> dict:
    """Every phenotyping system on the leaderboard: system -> (input, method), as the README describes it."""
    systems = {m: ("chart note" + (" + radiograph" if base_id(m) == "fusion_tfidf_rad" else ""), _model_method(m))
               for m in inp["ladder"]["method"]}
    return systems | PHENOTYPES | EVIDENCE


def phenotype_predictions(inp) -> tuple[pd.Series, dict, pd.Series]:
    """(truth, {system: status per review chart, NaN = no status}, note difficulty), indexed by visit_id.
    The one place the leaderboard's inputs are assembled; the judge scorecard (spec 012) reuses it."""
    preds = inp["preds"]
    key = inp["key"].reindex(preds.index)
    pred = {s: (preds[s] if s in preds else key[s]).where(lambda x: x.isin(LABELS)) for s in phenotype_systems(inp)}
    return preds["truth"], pred, key["difficulty"]


def _phenotyping(inp) -> tuple[str, pd.DataFrame]:
    reg = inp["registry"]
    systems = phenotype_systems(inp)
    truth, pred, level = phenotype_predictions(inp)
    tab = ladder_eval.ladder_table(truth, pred, n_boot=N_BOOT, seed=SEED, reference="").set_index("method")
    ranks = paired_rank_range({s: (pred[s] == truth).to_numpy() for s in systems})
    score = _shared_scorer()
    yn = {s: yes_no(truth, pred[s], score) for s in systems}
    links = {m["id"]: f"https://huggingface.co/{m['hf']}" for m in reg["models"] if m.get("hf")}
    out = [PHENOTYPE_TITLE, "",
           "Every system that assigns one of the six periodontal statuses, on the same 240 synthetic review "
           "charts against the generator's truth: models that read only the chart note, the rule phenotypes "
           "that combine the whole record, and each evidence type alone. **Rank** is the 95% range of the "
           "system's rank by exact status, over the same chart resamples as its CI (paired bootstrap): \"1–3\" "
           "means it plausibly ranks anywhere from 1st to 3rd.", "",
           PHENOTYPE_KEY + " *Coverage*: share of charts it gives a status for. *Stage IV caught*: share of "
           "stage IV patients called stage IV. *Unsafe errors*: mistakes that could harm a patient if acted on, "
           "e.g. a missed stage III–IV. Easy / medium / hard: exact status right when the note states the 2017 "
           "diagnosis (L1), states it in older terms (L2), or leaves it to be inferred from the findings (L3).", "",
           "| Rank | System | Input | Method | Exact status right (95% CI) | Sensitivity | Specificity | PPV | NPV | "
           "Coverage | Stage IV caught | Unsafe errors | Easy / medium / hard |",
           "|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    tab = tab.sort_values("accuracy", ascending=False, kind="stable")
    for s, r in tab.iterrows():
        b = base_id(s)
        name = f"[`{s}`]({links[b]})" if b in links else f"`{s}`"
        ok = pred[s] == truth
        levels = " / ".join(_pct(ok[level == lv].mean()) for lv in ("L1", "L2", "L3"))
        out.append(f"| {_rank(ranks[s])} | {name} | {systems[s][0]} | {systems[s][1]} | "
                   f"{_ci(r['accuracy'], r['acc_lo'], r['acc_hi'])} | "
                   + " | ".join(_pct(yn[s][k]) for k in ("sensitivity", "specificity", "ppv", "npv")) +
                   f" | {_pct(pred[s].notna().mean())} | {_pct(r['stage4_recall'])} | {_pct(r['unsafe_rate'])} | {levels} |")
    scored = {base_id(m) for m in inp["ladder"]["method"]}
    missing = []
    for m in reg["models"]:
        if m["id"] in scored:
            continue
        why = ("not a classifier; scored on its own task" if m.get("role") in ("entity_linking", "retrieval") else
               "needs a GPU" if re.search(r"large|longformer|27b", m["id"]) else "not scheduled yet")
        missing.append(f"[`{m['id']}`](https://huggingface.co/{m['hf']}) ({why})")
    out += ["", f"{NOT_RUN} " + "; ".join(missing) + ". MedGemma few-shot and LoRA runs are not done yet "
            "(LoRA needs a GPU)."]
    summary = tab.assign(rank=[_rank(ranks[s]) for s in tab.index], n_missing=len(missing),
                         **{k: [yn[s][k] for s in tab.index] for k in ("sensitivity", "specificity", "ppv")})
    return "\n".join(out), summary


def _deid(inp) -> tuple[str, pd.DataFrame]:
    d = inp["deid"]
    allt = d[d.tier == "all"].set_index("method")
    unseen = d[d.tier == "unseen"].set_index("method")
    asq = d[d.tier == "external"].set_index("method")
    mac = inp["maccrobat"].set_index("method")
    ci = [wilson(r.entity_recall * r.n_phi, r.n_phi) for r in allt.itertuples()]
    allt = allt.assign(lo=[c[0] for c in ci], hi=[c[1] for c in ci]).sort_values(
        ["entity_recall", "char_precision"], ascending=False, kind="stable")
    ranks = interval_rank_range(allt["lo"], allt["hi"])
    n_notes, n_phi = int(allt["n_notes"].iloc[0]), int(allt["n_phi"].iloc[0])

    def col(t, m, c, dec=0):
        return _pct(t.loc[m, c], dec) if m in t.index else "–"

    out = [DEID_TITLE, "",
           f"Every engine on the {n_notes} synthetic dental notes with fake PHI ({n_phi:,} identifiers, all tiers), "
           "ranked by identifiers caught, with a Wilson 95% CI. Per-identifier results aren't saved, so there is "
           "no paired bootstrap: **Rank** is the range the intervals allow, from only the engines clearly above "
           "counting to every engine whose interval reaches this one's counting.", "",
           DEID_KEY + " Catching identifiers protects patients; the false-alarm columns protect the text the AI "
           "reads, so read them together. *Unseen tier*: the notes no engine was written against. **ASQ-PHI**: "
           "1,051 synthetic clinical queries (MIT); *clean queries changed* = identifier-free queries altered. "
           "**MACCROBAT**: 200 real, published case reports (CC BY 4.0); its dates are the identifiers, and "
           "*clinical text damaged* = share of clinical terms cut. "
           "[More on these numbers](deidentification.md#how-to-read-the-numbers).", "",
           "| Rank | Engine | Identifiers caught (95% CI) | Caught, unseen tier | Removals that were identifiers | "
           "Dental terms damaged | ASQ-PHI: caught | ASQ-PHI: clean queries changed | MACCROBAT: dates caught | "
           "MACCROBAT: clinical text damaged |",
           "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for rank, (m, r) in zip(ranks, allt.iterrows()):
        out.append(f"| {_rank(rank)} | `{m}` | {_ci(r['entity_recall'], r['lo'], r['hi'])} | "
                   f"{col(unseen, m, 'entity_recall')} | {_pct(r['char_precision'])} | {_pct(r['decoy_damage'])} | "
                   f"{col(asq, m, 'entity_recall')} | {col(asq, m, 'hard_negative_damage')} | "
                   f"{col(mac, m, 'entity_recall')} | {col(mac, m, 'decoy_damage', 1)} |")
    out += ["", f"{NOT_RUN} " + ", ".join(f"`{m}`" for m in inp["deid_not_run"]["method"]) +
            " (cloud and LLM engines; each needs its service's credentials)."]
    summary = allt.assign(rank=[_rank(r) for r in ranks],
                          mac=[mac.loc[m, "entity_recall"] if m in mac.index else np.nan for m in allt.index])
    return "\n".join(out), summary


_HEAD = ("> **Synthetic data, scored against the generator's truth: not clinical performance.** Real model "
         "runs (CPU, 2026-10-26), not simulated; agreement with *simulated* reviewers is a dry run and isn't "
         "shown here. One leaderboard per capability; systems aren't ranked across them.")


def _by_best(tab: pd.DataFrame, groups, score: str) -> list[str]:
    best = tab.groupby("group")[score].max()
    return sorted(groups, key=lambda g: -best[g])


def _judge(inp) -> tuple[str, str]:
    """docs/results.md section and the README line for the LLM judge scorecard (spec 012)."""
    link = f"[judge results](docs/results.md#{anchor(JUDGE_TITLE)})"
    j = inp.get("judge")
    if j is None:
        sec = [JUDGE_TITLE, "", "**Not run yet.** Every system's answers scored against an LLM judge's own reading of "
               "each note, next to the truth, once `python/scripts/36_judge_scorecard.py --endpoint ...` or the "
               f"`judge_scorecard` job in dev has run; then also the *{DASHBOARD}* dashboard in Databricks."]
        line = (f"**LLM judge**: the same metrics against an LLM's reading of each note (LLM judgment, checked "
                f"against the truth): not run yet; {link}, then the *{DASHBOARD}* dashboard in Databricks.")
        return "\n".join(sec), line
    m, a, jd = j["judge_metrics"], j["judge_agreement"].set_index(["group", "value"]), j["judgments"]
    allr = a.loc[("all", "all")]
    who = ", ".join(f"`{e}`" for e in sorted(jd["endpoint"].unique()))
    sec = [JUDGE_TITLE, "",
           f"The same {int(allr['n'])} charts, each system's answers scored against the truth and against an LLM "
           f"judge's own reading of each note (**LLM judgment**: {who}, prompts "
           + ", ".join(f"`{v}`" for v in sorted(jd["prompt_version"].unique())) + "). The judge's agreement with the "
           "truth says how far it could stand in for an answer key on real notes; every number is computed in "
           f"code, never by the LLM. In Databricks: the *{DASHBOARD}* dashboard.", "",
           "| Charts | Judge gave a status | Judge agrees with truth (95% CI) | Kappa |", "|---|---:|---|---:|"]
    for (g, v), r in a.iterrows():
        if g in ("all", "difficulty"):
            sec.append(f"| {r['label']} ({int(r['n'])}) | {_pct(r['coverage'])} | {_ci(r['agreement'], r['ci_low'], r['ci_high'])} | "
                       f"{r['kappa']:.2f} |")
    ex = m[m.metric == "exact_status"].sort_values("vs_truth", ascending=False)
    sec += ["", "| System | Group | Exact status right, vs truth | vs judge | Difference | "
            "Judge-corrected accuracy where it answers (95% CI) |", "|---|---|---:|---:|---:|---|"]
    for r in ex.itertuples():
        corr = "–" if pd.isna(r.corrected_accuracy) else _ci(r.corrected_accuracy, r.ci_low, r.ci_high)
        sec.append(f"| `{r.system}` | {r.group} | {_pct(r.vs_truth, 1)} | {_pct(r.vs_judge, 1)} | "
                   f"{r.difference * 100:+.1f} pts | {corr} |")
    sec += ["", "Every metric (sensitivity, specificity, PPV, NPV, stage IV caught, unsafe errors, by note difficulty) "
            "both ways: `data/datasets/judge/judge_metrics.csv`."]
    line = (f"**LLM judge**: the same metrics against an LLM's reading of each note (LLM judgment, checked against "
            f"the truth): it agrees with the truth on {_pct(allr['agreement'])} of the charts it reads; {link}, "
            f"and the *{DASHBOARD}* dashboard in Databricks.")
    return "\n".join(sec), line


def details_markdown(inp: dict) -> str:
    """docs/results.md: the full tables."""
    return "\n\n".join([
        "# Results",
        "<!-- generated by python/scripts/35_readme_results.py from committed results; do not edit -->",
        _HEAD + " Sources: `data/datasets/ladder/`, `data/datasets/answer_key/`, `data/deid/`. "
        "Summary: [README](../README.md#results).",
        _phenotyping(inp)[0], _judge(inp)[0], _deid(inp)[0]]) + "\n"


def results_markdown(inp: dict) -> str:
    """The README block: the best system of each group, linking to the full tables."""
    _, ph = _phenotyping(inp)
    _, de = _deid(inp)
    ph = ph.assign(group=[phenotype_group(s) for s in ph.index])
    de = de.assign(group=[deid_group(m) for m in de.index])
    out = [_HEAD, "", PHENOTYPE_TITLE, "",
           "Best system in each group on the 240 review charts, groups ordered by their best. Rank: 95% range among all "
           f"{len(ph)} systems (paired bootstrap). " + PHENOTYPE_KEY, "",
           "| Group | Best system | Exact status right (95% CI) | Rank | Sensitivity | Specificity | PPV | Systems |",
           "|---|---|---|---|---:|---:|---:|---:|"]
    for g in _by_best(ph, PHENOTYPE_GROUPS, "accuracy"):
        sub = ph[ph.group == g]
        s, r = sub.index[0], sub.iloc[0]
        out.append(f"| {g} | `{s}` | {_ci(r['accuracy'], r['acc_lo'], r['acc_hi'])} | {r['rank']} | "
                   f"{_pct(r['sensitivity'])} | {_pct(r['specificity'])} | {_pct(r['ppv'])} | {len(sub)} |")
    out += ["", f"All {len(ph)} systems with NPV, coverage, stage IV, unsafe errors and results by note difficulty, "
            f"and the {int(ph['n_missing'].iloc[0])} models not run yet: "
            f"[full phenotyping table](docs/results.md#{anchor(PHENOTYPE_TITLE)}).", "", _judge(inp)[1], "",
            DEID_TITLE, "",
            f"Best engine in each group on the synthetic notes, groups ordered by their best. Rank: range among all {len(de)} engines "
            "(Wilson intervals). " + DEID_KEY, "",
            "| Group | Best engine | Identifiers caught (95% CI) | Rank | Removals that were identifiers | "
            "MACCROBAT: dates caught | Engines |",
            "|---|---|---|---|---:|---:|---:|"]
    for g in _by_best(de, DEID_GROUPS, "entity_recall"):
        sub = de[de.group == g]
        m, r = sub.index[0], sub.iloc[0]
        out.append(f"| {g} | `{m}` | {_ci(r['entity_recall'], r['lo'], r['hi'])} | {r['rank']} | "
                   f"{_pct(r['char_precision'])} | {_pct(r['mac'])} | {len(sub)} |")
    out += ["", f"All {len(de)} engines with the unseen tier, ASQ-PHI and MACCROBAT, and the engines not run yet: "
            f"[full de-identification table](docs/results.md#{anchor(DEID_TITLE)})."]
    return "\n".join(out)


def update_readme(text: str, block: str) -> str:
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    return f"{pre}{START}\n{block}\n{END}{post}"
