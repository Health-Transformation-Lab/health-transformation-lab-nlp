READERS_TITLE = "### Which AI reads the dental note best"
PHENOTYPE_TITLE = "### Combining all the evidence: the rule-based phenotype"
DEID_TITLE = "### Removing patient identifiers (de-identification)"
NOT_RUN = "**Not run yet:**"

PHENOTYPES = {"algorithm_v0": "rules, probing chart first (current phenotype, v0.1)",
              "algorithm_design": "rules, study-design order: exam form, diagnosis codes, note, chart"}
EVIDENCE = {"probing_chart": "probing chart alone", "notes": "chart note alone (regex reader)",
            "exam_form": "exam form alone", "proc_dx_planned": "diagnosis codes on planned procedures",
            "proc_dx_completed": "diagnosis codes on completed procedures",
            "proc_codes_planned": "procedure codes, planned", "proc_codes_completed": "procedure codes, completed",
            "radiograph_ai": "radiograph AI alone"}


def load_inputs() -> dict:
    lad = DATASETS_DIR / "ladder"
    return {"ladder": pd.read_csv(lad / "ladder_vs_truth.csv"),
            "preds": pd.read_csv(lad / "ladder_preds.csv").set_index("visit_id"),
            "by_diff": pd.read_csv(lad / "medgemma_vs_bert_by_difficulty.csv"),
            "key": pd.read_csv(DATASETS_DIR / "answer_key" / "review_key.csv").set_index("visit_id"),
            "registry": yaml.safe_load(MODELS_YAML.read_text()),
            "deid": pd.read_csv(DEID_DIR / "scores.csv"),
            "deid_not_run": pd.read_csv(DEID_DIR / "not_run.csv"),
            "maccrobat": pd.read_csv(DEID_DIR / "maccrobat_scores.csv")}


def base_id(method: str) -> str:
    """'modernbert-base+cw+s1+rules4' -> 'modernbert-base'."""
    return method.split("+", 1)[0]


def ci_rank(score, lo, hi) -> list[int]:
    return [1 + sum(lo_j > hi_i for lo_j in lo) for hi_i in hi]


def _ranked(df: pd.DataFrame, score: str, lo: str, hi: str) -> pd.DataFrame:
    """Rows sorted as leaderboards sort them: by rank, then score."""
    df = df.assign(rank=ci_rank(df[score], df[lo], df[hi]))
    return df.sort_values(["rank", score], ascending=[True, False], kind="stable")


def wilson(k: float, n: float, z: float = 1.96) -> tuple[float, float]:
    if not n:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def macro_f1(truth: pd.Series, pred: pd.Series) -> float:
    return float(f1_score(truth, pred.fillna("none"), labels=LABELS, average="macro", zero_division=0))


def _pct(x, d=0) -> str:
    return "–" if pd.isna(x) else f"{x:.{d}%}"


def _ci(x, lo, hi, d=1) -> str:
    return f"**{x:.{d}%}** ({lo:.{d}%}–{hi:.{d}%})"


def _hf_links(reg) -> dict:
    return {m["id"]: f"https://huggingface.co/{m['hf']}" for m in reg["models"] if m.get("hf")}


def _setting(method: str) -> str:
    b = base_id(method)
    s = ("keyword rules" if b == "note_rules" else
         "word-count model (TF-IDF)" if b == "tfidf_logreg" else
         "word counts + X-ray findings" if b == "fusion_tfidf_rad" else
         "large language model, no training (zero-shot)" if b.startswith("medgemma") else
         "BERT-type model trained on these charts")
    mods = {"cw": "rare stages weighted up", "s1": "2nd training run", "s2": "3rd training run",
            "rules4": "+ keyword rule for stage IV"}
    extra = [mods[m] for m in method.split("+")[1:] if m in mods]
    return ", ".join([s, *extra])


def _readers(inp) -> str:
    lad = _ranked(inp["ladder"].sort_values("accuracy", ascending=False), "accuracy", "acc_lo", "acc_hi")
    preds, links = inp["preds"], _hf_links(inp["registry"])
    lv = inp["by_diff"].pivot(index="method", columns="difficulty", values="accuracy")
    out = [READERS_TITLE, "",
           ("Each AI reads one dental chart note and picks one of six answers: healthy, gingivitis, or gum "
           "disease (periodontitis) stage I, II, III or IV. Tested on 240 made-up charts where the right "
           "answer is known."), "",
           ("- **Rank:** 1 is best. An AI ranks lower only when it is clearly worse, that is, its whole accuracy "
           "range sits below the other's; when the ranges overlap, they share a rank."),
           ("- **Accuracy:** share of charts answered correctly. In brackets: the range the true value most "
           "likely falls in (95% confidence interval)."),
           ("- **Balanced score:** accuracy with each of the six answers counting equally, so missing the rare "
           "stages pulls it down (macro-F1, 0 to 1)."),
           "- **Stage IV caught:** share of the most severe cases the AI got right.",
           ("- **Unsafe errors:** share of answers with a mistake that could harm the patient if acted on, such "
           "as calling severe disease healthy."),
           ("- **Easy / medium / hard:** accuracy when the note names the diagnosis in today's terms, names it "
           "in older terms, or only lists the findings."), "",
           "| Rank | AI | Type | Accuracy (95% range) | Balanced score | Stage IV caught | Unsafe errors | Easy / medium / hard |",
           "|---:|---|---|---|---:|---:|---:|---|"]
    for _, r in lad.iterrows():
        m, b, rank = r["method"], base_id(r["method"]), int(r["rank"])
        name = f"[`{m}`]({links[b]})" if b in links else f"`{m}`"
        levels = (" / ".join(_pct(lv.loc[m, k]) for k in ("L1", "L2", "L3")) if m in lv.index else "–")
        out.append(f"| {rank} | {name} | {_setting(m)} | {_ci(r['accuracy'], r['acc_lo'], r['acc_hi'])} | "
                   f"{macro_f1(preds['truth'], preds[m]):.2f} | {_pct(r['stage4_recall'])} | "
                   f"{_pct(r['unsafe_rate'])} | {levels} |")
    scored = {base_id(m) for m in lad["method"]}
    missing = []
    for m in inp["registry"]["models"]:
        if m["id"] in scored:
            continue
        why = ("not a classifier; scored on its own task" if m.get("role") in ("entity_linking", "retrieval") else
               "needs a GPU" if re.search(r"large|longformer|27b", m["id"]) else "not scheduled yet")
        missing.append(f"[`{m['id']}`](https://huggingface.co/{m['hf']}) ({why})")
    out += ["", f"{NOT_RUN} " + "; ".join(missing) + ". MedGemma few-shot and LoRA runs are not done yet "
            "(LoRA needs a GPU)."]
    return "\n".join(out)


def _phenotypes(inp) -> str:
    key = inp["key"]
    truth = key["truth_status"]
    systems = {**PHENOTYPES, **EVIDENCE}
    preds = {s: key[s].where(key[s].isin(LABELS)) for s in systems}
    tab = ladder_eval.ladder_table(truth, preds, reference="").set_index("method")
    tab["coverage"] = [preds[s].notna().mean() for s in tab.index]
    tab["acc_answered"] = [(preds[s] == truth)[preds[s].notna()].mean() for s in tab.index]
    tab = _ranked(tab.sort_values("accuracy", ascending=False), "accuracy", "acc_lo", "acc_hi")
    out = [PHENOTYPE_TITLE, "",
           ("The *phenotype* is a set of rules that decides each patient's status from everything in the "
           "record: exam form, diagnosis codes, the note and the probing chart. When these disagree, it trusts "
           "them in a fixed order and takes the first that gives an answer. The other rows score each source "
           "on its own. Same 240 charts as above."), "",
           "- **Answers given:** share of charts where that evidence gives any status at all.",
           ("- **Accuracy** counts a chart with no answer as wrong; **accuracy where it answers** leaves those "
           "charts out. Other columns as in the table above."), "",
           ("| Rank | System | What it uses | Accuracy (95% range) | Answers given | Accuracy where it answers | "
           "Stage IV caught | Unsafe errors |"),
           "|---:|---|---|---|---:|---:|---:|---:|"]
    for s, r in tab.iterrows():
        unsafe = unsafe_rates(truth, preds[s])["unsafe_rate"]
        out.append(f"| {int(r['rank'])} | `{s}` | {systems[s]} | {_ci(r['accuracy'], r['acc_lo'], r['acc_hi'])} | "
                   f"{_pct(r['coverage'])} | {_pct(r['acc_answered'])} | {_pct(r['stage4_recall'])} | {_pct(unsafe)} |")
    return "\n".join(out)


def _deid(inp) -> str:
    d = inp["deid"]
    allt = d[d.tier == "all"].set_index("method")
    unseen = d[d.tier == "unseen"].set_index("method")
    asq = d[d.tier == "external"].set_index("method")
    mac = inp["maccrobat"].set_index("method")
    ci = [wilson(r.entity_recall * r.n_phi, r.n_phi) for r in allt.itertuples()]
    allt = _ranked(allt.assign(lo=[c[0] for c in ci], hi=[c[1] for c in ci]).sort_values(
        ["entity_recall", "char_precision"], ascending=False), "entity_recall", "lo", "hi")
    n_notes, n_phi = int(allt["n_notes"].iloc[0]), int(allt["n_phi"].iloc[0])
    def col(t, m, c, d=0):
        return _pct(t.loc[m, c], d) if m in t.index else "–"
    out = [DEID_TITLE, "",
           ("Before any AI reads a note, names, dates, phone numbers and other identifiers have to come out. "
           f"Each engine ran on {n_notes} made-up dental notes with {n_phi:,} fake identifiers planted in them. "
           "Two kinds of mistake pull against each other, so read the columns together: leaving an identifier "
           "in harms the patient; cutting ordinary text harms what the AI can read."), "",
           ("- **Identifiers removed:** share taken out; leaving even one character counts as a leak. Ranked "
           "by this. In brackets: the 95% range (Wilson interval)."),
           "- **New kinds removed:** the same, on identifiers written in ways no engine was built for.",
           "- **Precision:** share of the text an engine cut that really was an identifier.",
           ("- **Dental terms damaged:** share of dental terms that look like identifiers (Glickman, Gracey "
           "11/12) cut by mistake."),
           ("- **ASQ-PHI** (1,051 made-up clinical questions, MIT licence): identifiers removed, and how often "
           "a question with no identifiers got changed anyway."),
           "- **MACCROBAT** (200 real published case reports, CC BY 4.0): dates removed, and medical terms cut.",
           "",
           "[How to read these](docs/deidentification.md#how-to-read-the-numbers).", "",
           ("| Rank | Engine | Identifiers removed (95% range) | New kinds removed | Precision | Dental terms damaged | "
           "ASQ-PHI removed | ASQ-PHI changed anyway | MACCROBAT dates removed | MACCROBAT terms cut |"),
           "|---:|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m, r in allt.iterrows():
        out.append(f"| {int(r['rank'])} | `{m}` | {_ci(r['entity_recall'], r['lo'], r['hi'])} | {col(unseen, m, 'entity_recall')} | "
                   f"{_pct(r['char_precision'])} | {_pct(r['decoy_damage'])} | {col(asq, m, 'entity_recall')} | "
                   f"{col(asq, m, 'hard_negative_damage')} | {col(mac, m, 'entity_recall')} | "
                   f"{col(mac, m, 'decoy_damage', 1)} |")
    nr = inp["deid_not_run"]["method"]
    out += ["", f"{NOT_RUN} " + ", ".join(f"`{m}`" for m in nr) +
            " (cloud and LLM engines; each needs its service's credentials)."]
    return "\n".join(out)


def results_markdown(inp: dict) -> str:
    head = ("> **Synthetic (made-up) data, checked against answers the data generator knows: not clinical "
            "performance.** "
            "Every number below comes from actually running the model (on CPU, 2026-10-26); none is simulated. "
            "Sources: `data/datasets/ladder/`, `data/datasets/answer_key/`, `data/deid/`.")
    return "\n\n".join([head, _readers(inp), _phenotypes(inp), _deid(inp)])


def update_readme(text: str, block: str) -> str:
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    return f"{pre}{START}\n{block}\n{END}{post}"
