"""Results leaderboards, one per capability (phenotyping, de-identification): a short summary in
the README (the best system of each group, linking down) and the full tables in docs/results.md.

Reported the way the more careful public model leaderboards report: one row per system with its
setting, the primary score with a 95% CI, and a 95% rank range (where the system plausibly ranks)
instead of a single rank. There is no overall rank across capabilities.

- Phenotyping: every system that assigns a periodontal status (note-reading models, the rule
  phenotypes, each evidence type alone) on the same 240 review charts against the same truth.
  Rank ranges come from a paired bootstrap: the same chart resamples as the accuracy CIs
  (ladder_eval.ladder_table), each system ranked within each resample.
- De-identification: per-identifier results aren't saved, so no bootstrap; the rank range is
  read from the Wilson intervals (best case: only engines clearly above count; worst case:
  every engine whose interval reaches this one's counts).

Everything is read from committed results; nothing is re-run. Synthetic data scored against the
generator's truth: not clinical performance.

    python scripts/35_readme_results.py           # rewrite the README block and docs/results.md
    python scripts/35_readme_results.py --check   # exit 1 if either is stale
"""

