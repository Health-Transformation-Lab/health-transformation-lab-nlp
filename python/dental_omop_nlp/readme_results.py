PHENOTYPE_GROUPS = ("Rule phenotype, whole record", "Fine-tuned note model + rules for stage IV",
                    "Fine-tuned note model", "Zero-shot LLM on the note", "Note baselines (rules, TF-IDF)",
                    "One evidence type alone")
DEID_GROUPS = ("Combined: ML + regex + guard", "Single ML engine", "Regex only")
_BASELINES = ("note_rules", "tfidf_logreg", "fusion_tfidf_rad")


def phenotype_group(system: str) -> str:
    b = base_id(system)
    if system in PHENOTYPES:
        return PHENOTYPE_GROUPS[0]
    if system in EVIDENCE:
        return PHENOTYPE_GROUPS[5]
    if b.startswith("medgemma"):
        return PHENOTYPE_GROUPS[3]
    if b in _BASELINES:
        return PHENOTYPE_GROUPS[4]
    return PHENOTYPE_GROUPS[1] if system.endswith("+rules4") else PHENOTYPE_GROUPS[2]


def deid_group(engine: str) -> str:
    ml = "hf_" in engine or "presidio" in engine
    if engine.startswith("routed") or (ml and "regex" in engine):
        return DEID_GROUPS[0]
    return DEID_GROUPS[1] if ml else DEID_GROUPS[2]


def anchor(title: str) -> str:
    """GitHub's heading anchor."""
    return re.sub(r"[^a-z0-9 -]", "", title.lstrip("# ").lower()).replace(" ", "-")


