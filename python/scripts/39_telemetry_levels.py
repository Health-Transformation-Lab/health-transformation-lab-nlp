"""Measure which traced functions are too low-level to trace by default (spec 014: verbosity levels).

    python scripts/39_telemetry_levels.py [--max-calls-per-parent 20] [--min-ms 0.5]

Runs representative pipelines, each in its own process as CI does, with DENTAL_TELEMETRY_PROFILE set:
every @traced call is counted (calls per parent call, time per call), whatever the exporter. A function called more than
--max-calls-per-parent times under one parent call, or cheaper than --min-ms and called that often,
is `detail`: off at the default level `call`, on with DENTAL_TELEMETRY_LEVEL=detail. Writes
python/health_transformation_lab_nlp/telemetry_levels.yaml; entries marked `manual: true` are kept as edited, and
functions these runs don't reach keep their old level (or default to `call`).

The pipelines rewrite their own outputs with the same seeds, so committed data doesn't change.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

import yaml

from health_transformation_lab_nlp import telemetry
from health_transformation_lab_nlp.paths import REPO_ROOT

RUNS = [                                    # (script, argv): fast, seeded, cover the package's main paths
    ("10_build_study.py", []),
    ("18_phenotype_order.py", ["--simulated"]),
    ("19_prevalence.py", []),
    ("20_data_quality.py", []),
    ("22_build_sites.py", []),
    ("37_cal_reliability.py", []),
    ("35_readme_results.py", []),
]

ap = argparse.ArgumentParser()
ap.add_argument("--max-calls-per-parent", type=int, default=20)
ap.add_argument("--min-ms", type=float, default=0.5)
args = ap.parse_args()

python_dir = REPO_ROOT / "python"
with tempfile.TemporaryDirectory() as tmp:
    out = os.path.join(tmp, "profile.jsonl")
    env = {**os.environ, "DENTAL_TELEMETRY_PROFILE": out, "DENTAL_TELEMETRY": "off"}
    for script, argv in RUNS:
        print(f"profiling {script} ...", flush=True)
        subprocess.run([sys.executable, f"scripts/{script}", *argv], cwd=python_dir, env=env, check=True,
                       stdout=subprocess.DEVNULL)
    with open(out, encoding="utf-8") as f:
        stats = telemetry.merge_profiles([json.loads(line) for line in f])

new = telemetry.classify(stats, args.max_calls_per_parent, args.min_ms)
old = yaml.safe_load(telemetry.LEVELS_FILE.read_text()) if telemetry.LEVELS_FILE.exists() else {}
merged = telemetry.merge_levels(old or {}, new)
header = ("# Verbosity level of each @traced function (spec 014). Generated by scripts/39_telemetry_levels.py\n"
          "# from measured calls; `detail` functions are traced only with DENTAL_TELEMETRY_LEVEL=detail.\n"
          "# Edit a level by hand and add `manual: true` to keep it when the script runs again.\n")
telemetry.LEVELS_FILE.write_text(header + yaml.safe_dump(merged, sort_keys=True, width=120))
n_detail = sum(v["level"] == "detail" for v in merged.values())
print(f"{len(merged)} functions measured: {n_detail} detail, {len(merged) - n_detail} call")
for name, v in merged.items():
    if v["level"] == "detail":
        print(f"  detail  {name:45s} {v['reason']}")
